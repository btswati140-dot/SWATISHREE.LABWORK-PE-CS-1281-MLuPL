# run_pipeline.py
import os
from shoptools import Machine, SpecViolation

def run_pipeline():
    input_path = "data/shift_log.txt"
    report_path = "data/report.txt"
    rejects_path = "data/rejects.csv"

    # 1. Ensure output directory exists
    os.makedirs("data", exist_ok=True)

    if not os.path.exists(input_path):
        print(f"Error: Input file '{input_path}' not found. Run your log generator first.")
        return

    # 2. Commission machine
    lathe = Machine(machine_id="M-01", operator="Tariyan", tolerance=0.02)

    print(f"Reading records from '{input_path}'...")

    # 3. Read -> Parse -> Validate
    with open(input_path, "r") as f:
        for line_num, raw_line in enumerate(f, start=1):
            cleaned_line = raw_line.strip()

            # Skip completely empty file lines if any exist
            if not cleaned_line:
                continue

            try:
                # process_job parses float, checks physical/math limits, and bins parts
                lathe.process_job(cleaned_line)
            except SpecViolation as e:
                # Catch custom domain exceptions and catalog rejects
                lathe.record_rejection(e.bad_input, e.reason)

    # 4. Aggregate: Generate Human Report & Rejects Table Data
    summary_text = lathe.get_summary()

    # 5. Write outputs
    # Write human-readable report
    with open(report_path, "w") as rep_file:
        rep_file.write(summary_text)

    # Write CSV rejects table (Comma-separated: Input, Reason)
    with open(rejects_path, "w") as rej_file:
        rej_file.write("Bad Input,Reason\n")
        for rej in lathe.rejects:
            # Escape commas or quotes if needed, wrap input in quotes for safety
            rej_file.write(f'"{rej["input"]}","{rej["reason"]}"\n')

    print(f"Pipeline complete!")
    print(f" -> Human report written to: {report_path}")
    print(f" -> Rejects CSV written to:    {rejects_path}")


if __name__ == "__main__":
    run_pipeline()

