# shoptools.py
import math
import re

class SpecViolation(Exception):
    """Custom domain exception raised when a part breaches quality, type, or safety specs."""
    def __init__(self, bad_input, reason):
        self.bad_input = bad_input
        self.reason = reason
        super().__init__(f"Input {repr(bad_input)} rejected: {reason}")


class Machine:
    def __init__(self, machine_id: str, operator: str, tolerance: float):
        self.__machine_id = machine_id
        self.__operator = operator
        self.__tolerance = tolerance
        self.__status = "Idle"

        self.__total = 0
        self.__pass = 0
        self.__undersize = 0
        self.__oversize = 0
        self.__refused = 0
        self.__valid_measurements = []
        self.rejects = []

    @property
    def machine_id(self) -> str:
        return self.__machine_id

    @property
    def total_parts(self) -> int:
        return self.__total

    def status(self) -> str:
        return self.__status

    def record_rejection(self, bad_input, reason: str):
        self.__refused += 1
        self.rejects.append({"input": repr(bad_input), "reason": reason})

    def process_job(self, raw_input) -> str:
        """
        Operating method using compiled regular expression parsing.
        Expected log line format: 'PART-CODE , MEASUREMENT , SHIFT'
        Example: 'PCV-101,  10.01  , A'
        """
        self.__total += 1

        # Ensure input is a string for regex matching
        if not isinstance(raw_input, str):
            raise SpecViolation(raw_input, f"TypeError: Expected string log record, got {type(raw_input).__name__}")

        # --- NEW REGEX PARSER ---
        # Pattern Breakdown:
        # ^([A-Z]{3}-\d{3}) -> Field 1: Part code shape (3 uppercase letters, hyphen, 3 digits e.g. PCV-101)
        # \s*,\s*         -> Tolerates any spaces around the comma separator
        # ([+-]?\d*\.?\d+)  -> Field 2: Numeric measurement value
        # \s*,\s*         -> Tolerates any spaces around the second comma separator
        # ([A-Za-z0-9]+)$   -> Field 3: Shift or Operator ID
        pattern = re.compile(r"^([A-Z]{3}-\d{3})\s*,\s*([+-]?\d*\.?\d+)\s*,\s*([A-Za-z0-9]+)$")
        match = pattern.match(raw_input.strip())

        if not match:
            raise SpecViolation(raw_input, "Parsing Error: Log line format does not match required shape (PCV-XXX , value , shift)")

        # Pull all three fields out in one atomic call
        part_code, raw_dia, shift_id = match.groups()

        # --- OLD SPLIT-BASED PARSER (Retained for Audit & Comparison) ---
        # NOTE ON SURVIVAL:
        # The old split-based parser survived simple single-value inputs (like '10.01' or 'N/A')
        # but completely failed structured multi-field records, messy internal whitespace,
        # and missing comma separators.
        # The new Regex parser survived significantly more edge cases because it validates
        # structural shape and isolates fields cleanly before casting or math validation occurs.
        #
        # old_parts = raw_input.split(',')
        # if len(old_parts) != 3:
        #     raise SpecViolation(raw_input, "Old Split Error: Incorrect field count")
        # part_code = old_parts[0].strip()
        # raw_dia = old_parts[1].strip()
        # shift_id = old_parts[2].strip()
        # -------------------------------------------------------------

        # 2. Mathematical & Physical Sanity Checks on extracted measurement
        try:
            dia = float(raw_dia)
        except ValueError:
            raise SpecViolation(raw_input, f"Parsing Error: Could not convert measurement '{raw_dia}' to float")

        if math.isnan(dia):
            raise SpecViolation(raw_input, "Math Error: Value is NaN")
        if not math.isfinite(dia):
            raise SpecViolation(raw_input, "Math Error: Value is infinite")
        if dia < 0.0:
            raise SpecViolation(raw_input, "Physics Error: Negative dimension impossible")

        # 3. Operational Safety Interlock
        deviation = dia - 10.0
        if abs(deviation) > 0.5:
            self.__status = "Error - Interlock Tripped"
            raise SpecViolation(raw_input, f"Safety Hazard: Deviation {round(deviation, 3)}mm exceeds ±0.5mm threshold")

        # 4. Standard Quality Binning
        self.__status = "Running"
        self.__valid_measurements.append(dia)

        lower_limit = 10.0 - self.__tolerance
        upper_limit = 10.0 + self.__tolerance

        if dia < lower_limit:
            self.__undersize += 1
            return f"PASS [{part_code} / Shift {shift_id}] -> UNDERSIZE ({dia}mm)"
        elif dia <= upper_limit:
            self.__pass += 1
            return f"PASS [{part_code} / Shift {shift_id}] -> PASS ({dia}mm)"
        else:
            self.__oversize += 1
            return f"PASS [{part_code} / Shift {shift_id}] -> OVERSIZE ({dia}mm)"

    def get_summary(self) -> str:
        avg_dia = sum(self.__valid_measurements) / len(self.__valid_measurements) if self.__valid_measurements else 0.0
        return (
            f"=== MACHINE {self.__machine_id} SHIFT REPORT ===\n"
            f"Operator: {self.__operator} | Status: {self.status()}\n"
            f"Total Processed: {self.__total} | Valid Measured: {len(self.__valid_measurements)}\n"
            f"Pass: {self.__pass} | Under: {self.__undersize} | Over: {self.__oversize} | Refused: {self.__refused}\n"
            f"Guarded Average Diameter: {round(avg_dia, 3)}mm\n"
        )

