import math

class Machine:
    def __init__(self, machine_id: str, operator: str, tolerance: float):
        self.__machine_id = machine_id
        self.__operator = operator
        self.__tolerance = tolerance
        self.__status = "Idle"

        # Internal counters and audit logs
        self.__total = 0
        self.__pass = 0
        self.__undersize = 0
        self.__oversize = 0
        self.__refused = 0
        self.__valid_measurements = []
        self.rejects = []  # Carrying bad input and reason

    @property
    def machine_id(self) -> str:
        return self.__machine_id

    @property
    def total_parts(self) -> int:
        return self.__total

    def status(self) -> str:
        return self.__status

    def process_raw_input(self, raw_input) -> str:
        """Hardened parser with named exception clauses and rigorous validation."""
        self.__total += 1

        # 1. Type & Parsing Safety (Named Exceptions)
        try:
            # Handle string with trailing units like "10.01mm"
            if isinstance(raw_input, str):
                cleaned = raw_input.lower().replace("mm", "").strip()
                dia = float(cleaned)
            else:
                dia = float(raw_input) # Will raise TypeError/ValueError for unsupported types like lists or None

        except TypeError as e:
            self.__refused += 1
            self.rejects.append({"input": repr(raw_input), "reason": f"TypeError: Invalid data type ({e})"})
            return f"REFUSED: Invalid type."
        except ValueError as e:
            self.__refused += 1
            self.rejects.append({"input": repr(raw_input), "reason": f"ValueError: Could not parse to float ({e})"})
            return f"REFUSED: Unparsable format."

        # 2. Mathematical & Physical Sanity Checks (NaN, Inf, Negatives)
        if math.isnan(dia):
            self.__refused += 1
            self.rejects.append({"input": repr(raw_input), "reason": "MathError: Value is NaN (Not a Number)"})
            return f"REFUSED: NaN detected."

        if not math.isfinite(dia):
            self.__refused += 1
            self.rejects.append({"input": repr(raw_input), "reason": "MathError: Value is infinite"})
            return f"REFUSED: Infinite value detected."

        if dia < 0.0:
            self.__refused += 1
            self.rejects.append({"input": repr(raw_input), "reason": "PhysicsError: Negative dimension impossible"})
            return f"REFUSED: Negative physical dimension."

        # 3. Operational Safety Interlock (Extreme Outliers)
        deviation = dia - 10.0
        if abs(deviation) > 0.5:
            self.__refused += 1
            self.__status = "Error - Interlock Tripped"
            self.rejects.append({"input": repr(raw_input), "reason": f"SafetyError: Deviation {round(deviation, 3)}mm exceeds ±0.5mm limit"})
            return f"REFUSED: Safety threshold exceeded."

        # 4. Standard Quality Control Binning
        self.__status = "Running"
        self.__valid_measurements.append(dia)

        lower_limit = 10.0 - self.__tolerance
        upper_limit = 10.0 + self.__tolerance

        if dia < lower_limit:
            self.__undersize += 1
            return f"-> UNDERSIZE ({dia}mm)"
        elif dia <= upper_limit:
            self.__pass += 1
            return f"-> PASS ({dia}mm)"
        else:
            self.__oversize += 1
            return f"-> OVERSIZE ({dia}mm)"

    def get_summary(self) -> str:
        """Generates report and guarded average calculation."""
        # Guarded average: avoids ZeroDivisionError if all parts are rejected
        if len(self.__valid_measurements) > 0:
            avg_dia = sum(self.__valid_measurements) / len(self.__valid_measurements)
        else:
            avg_dia = 0.0

        return (
            f"=== MACHINE {self.__machine_id} SHIFT REPORT ===\n"
            f"Operator: {self.__operator} | Status: {self.status()}\n"
            f"Total Processed: {self.__total} | Valid Measured: {len(self.__valid_measurements)}\n"
            f"Pass: {self.__pass} | Under: {self.__undersize} | Over: {self.__oversize} | Refused: {self.__refused}\n"
            f"Guarded Average Diameter: {round(avg_dia, 3)}mm\n"
        )

