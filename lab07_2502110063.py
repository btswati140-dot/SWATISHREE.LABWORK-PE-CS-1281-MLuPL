    def machine_id(self) -> str:
        return self.__machine_id

    @property
    def total_parts(self) -> int:
        """Exposes total workload for load balancing and busiest-machine calculations."""
        return self.__total

    def status(self) -> str:
        return self.__status

    def process_job(self, dia: float) -> str:
        """Processes a part, enforces safety guards, and updates internal counters."""
        self.__total += 1
        deviation = dia - 10.0

        if abs(deviation) > 0.5:
            self.__refused += 1
            self.__status = "Error - Interlock Tripped"
            return f"REFUSED: {dia}mm exceeds safety threshold."

        self.__status = "Running"
        lower_limit = 10.0 - self.__tolerance
        upper_limit = 10.0 + self.__tolerance

        if dia < lower_limit:
            self.__undersize += 1
            return f"-> UNDERSIZE ({dia}mm)"
        elif dia <= upper_limit:
            self.__pass += 1
            return f"-> PASS ({dia}mm)"
        else:
            self.__oversize += 1
            return f"-> OVERSIZE ({dia}mm)"

    def get_summary(self) -> dict:
        """Returns internal metrics for plant-level reporting."""
