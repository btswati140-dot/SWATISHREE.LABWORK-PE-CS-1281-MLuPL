class Machine:
    def __init__(self, machine_id: str, operator: str, tolerance_limit: float):
        self.machine_id = machine_id
        self.operator = operator
        self.tolerance_limit = tolerance_limit
        self.status = "Idle"

    def __str__(self) -> str:
        """Acts as a physical nameplate attached to the machine."""
        return f"[Machine: {self.machine_id} | Operator: {self.operator} | Tolerance Limit: ±{self.tolerance_limit}mm | Status: {self.status}]"

    def run_cycle(self, measurement: float) -> str:
        """Working method: processes a part measurement against this machine's specific limit."""
        self.status = "Running"
        if abs(measurement - 10.0) <= self.tolerance_limit:
            return f"{self.machine_id} -> PASS (Deviation: {round(measurement - 10.0, 3)}mm)"
        else:
            return f"{self.machine_id} -> OUT OF SPEC"


