for line in logs:
    data = line.split(",")

    part_code = data[0].strip()
    diameter = float(data[1].strip())

    catalogue[part_code] = diameter


# Tool 1: Safe lookup
def lookup(catalogue, code):
    return catalogue.get(code, "Part code not found")


# Tool 2: Find scrap codes
def scrap_codes(catalogue):
    return {
        code
        for code, dia in catalogue.items()
        if dia < 24.90 or dia > 25.10
    }


