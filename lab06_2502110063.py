# shoptools.py

def inspect(dia: float) -> str:
    """Categorizes a part diameter into a quality control bin label."""
    if dia < 9.8:
        return "undersize"
    elif dia <= 10.2:
        return "pass"
    else:
        return "oversize"


def tally(labels: list[str]) -> dict[str, int]:
    """Counts occurrences of each bin label in a sequence."""
    counts = {"undersize": 0, "pass": 0, "oversize": 0}
    for label in labels:
        counts[label] = counts.get(label, 0) + 1
    return counts


def report(shift: str, counts: dict[str, int]) -> str:
    """Formats shift totals into a single summary string."""
    total = sum(counts.values())
    passed = counts.get("pass", 0)
    under = counts.get("undersize", 0)
    over = counts.get("oversize", 0)
    return f"Shift {shift} | Total: {total} | Pass: {passed} | Under: {under} | Over: {over}"