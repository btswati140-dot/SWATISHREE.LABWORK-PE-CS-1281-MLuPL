import random

consecutive_accepts = 0
total_parts = 0
max_attempts = 500

while consecutive_accepts < 5 and total_parts < max_attempts:

    diameter = round(random.uniform(24.90, 25.10), 2)
    total_parts += 1

    print("Part", total_parts, "Diameter:", diameter, "mm")

    if 24.95 <= diameter <= 25.05:
        print("ACCEPT")
        consecutive_accepts += 1

    else:
        print("NOT ACCEPT - Streak reset")
        consecutive_accepts = 0

    print("Consecutive ACCEPTs:", consecutive_accepts)
    print("--------------------------------")

if consecutive_accepts == 5:
    print("\nSUCCESS! Five consecutive ACCEPTs achieved.")
    print("Total parts required:", total_parts)

else:
    print("\nSAFETY LIMIT REACHED!")
    print("Maximum attempts:", max_attempts)
    print("Five consecutive ACCEPTs were not achieved.")
    print("Total parts inspected:", total_parts)