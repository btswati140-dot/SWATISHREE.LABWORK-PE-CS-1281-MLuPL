"""IT10"""

import random

accept = 0
rework = 0
scrap = 0

for i in range(10):
    diameter = random.uniform(24.90, 25.10)
    diameter = round(diameter, 2)

    print("\nPart", i + 1, "Diameter:", diameter, "mm")

    if 24.95 <= diameter <= 25.05:
        print("Bin: ACCEPT")
        accept += 1

    elif 24.90 <= diameter < 24.95 or 25.05 < diameter <= 25.10:
        print("Bin: REWORK")
        rework += 1

    else:
        print("Bin: SCRAP")
        scrap += 1

print("\n========== SHIFT REPORT ==========")
print("ACCEPT:", accept)
print("REWORK:", rework)
print("SCRAP:", scrap)
print("Total parts:", accept + rework + scrap)
print("==================================")

