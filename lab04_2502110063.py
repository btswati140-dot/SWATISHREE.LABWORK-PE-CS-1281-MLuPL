import random

accept = 0
rework = 0
scrap = 0
inspected = 0

mode = input("Choose inspection mode (HALT/SKIP): ").upper()

for i in range(10):
    diameter = round(random.uniform(24.90, 25.10), 2)
    inspected += 1

    print("\nPart", i + 1, "Diameter:", diameter, "mm")

    if 24.95 <= diameter <= 25.05:
        print("Bin: ACCEPT")
        accept += 1

    elif 24.90 <= diameter < 24.95 or 25.05 < diameter <= 25.10:
        print("Bin: REWORK")
        rework += 1

    else:
        print("Bin: SCRAP")
        scrap += 1

        if mode == "HALT":
            print("SCRAP detected! Stopping batch.")
            break

        elif mode == "SKIP":
            print("SCRAP logged. Continuing inspection.")
            continue

print("\n========== SHIFT REPORT ==========")
print("Inspection mode:", mode)
print("Parts inspected:", inspected)
print("ACCEPT:", accept)
print("REWORK:", rework)
print("SCRAP:", scrap)
print("==================================")

