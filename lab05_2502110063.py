# DAY AND NIGHT PRODUCTION LOGS

day_logs = [
    "P101,25.04,DAY",
    "P102,24.92,DAY",
    "P103,25.08,DAY",
    "P104,25.01,DAY",
    "P105,24.94,DAY"
]

night_logs = [
    "P103,25.09,NIGHT",
    "P104,25.00,NIGHT",
    "P106,24.91,NIGHT",
    "P107,25.07,NIGHT",
    "P108,25.02,NIGHT"
]

# Separate scrap-code lists
day_scrap = []
night_scrap = []

def analyse_shift(logs, shift_name, scrap_codes):

    accepted = []
    rework = []
    scrap = []

    for line in logs:
        data = line.split(",")

        part_code = data[0].strip()
        dia = float(data[1].strip())

        if 24.95 <= dia <= 25.05:
            accepted.append(dia)

        elif 24.90 <= dia < 24.95 or 25.05 < dia <= 25.10:
            rework.append(dia)

        else:
            scrap.append(dia)
            scrap_codes.append(part_code)

    total = len(logs)

    if total > 0:
        accept_rate = (len(accepted) / total) * 100
    else:
        accept_rate = 0

    print("\n---", shift_name, "SHIFT REPORT ---")
    print("Total parts:", total)
    print("Accepted:", len(accepted))
    print("Rework:", len(rework))
    print("Scrap:", len(scrap))
    print("Accept rate:", round(accept_rate, 2), "%")
    print("Scrap codes:", scrap_codes)


# Analyse both shifts
analyse_shift(day_logs, "DAY", day_scrap)
analyse_shift(night_logs, "NIGHT", night_scrap)

# SET COMPARISON
day_set = set(day_scrap)
night_set = set(night_scrap)

common_scrap = day_set & night_set
unique_scrap = day_set ^ night_set

print("\n========== SCRAP COMPARISON ==========")
print("Common scrap codes:", sorted(common_scrap))
print("Unique scrap codes:", sorted(unique_scrap))
